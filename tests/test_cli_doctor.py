"""Tests for `ol doctor` — the config validation checklist (OL#92).

Contract (scenarios 4-7):
4. `ol doctor --config <valid>` on a valid config (generated by `ol init`)
   → exit 0, output contains "[PASS]" and all 5 checks.
5. `ol doctor` on a config where a role has only 1 model → exit
   ExitCode.PIPELINE_ERROR, output contains "[FAIL]" AND the
   "run 'ol init'" hint.
6. `ol doctor` on a valid pool but a referenced ${VAR} is unset
   (a referenced ${VAR} deleted + .env auto-load neutralized) → exit 1,
   "[FAIL]" for the env check.
7. `--json` emits ONE parseable object {"ok": bool, "checks": {5 keys}}.
8. `doctor` appears in `ol --help` output.
"""
from __future__ import annotations

import json
import re

from typer.testing import CliRunner

from cli._shared import ExitCode
from ol_cli import app

runner = CliRunner()

ENV = {"OMNI_TEST_FAKE_LLM": "1"}

# Human-readable checklist names (must match src/cli/doctor.py display).
CHECK_NAMES = (
    "config file exists",
    "yaml parses",
    "load_config succeeds",
    "min models per role",
    "env vars resolve",
)

# Machine-readable JSON keys (must match src/cli/doctor.py --json).
JSON_KEYS = (
    "config_file_exists",
    "yaml_parses",
    "load_config_succeeds",
    "min_models_per_role",
    "env_vars_resolve",
)

# A config whose translation role has only 1 model → schema ValueError
# (check_min_models_per_role requires >=2). Other roles have 2 each so
# the failure is isolated to the translation role.
ONE_MODEL_ROLE_YAML = """\
project_id: test
source_lang: en
target_lang: zh
llm_pool:
  translation:
    - provider: openai
      model: minimaxai/minimax-m3
      priority: 1
      role: translation
      api_key: "${NVIDIA_NIM_API_KEY}"
      base_url: "https://integrate.api.nvidia.com/v1"
  judging:
    - provider: openai
      model: minimaxai/minimax-m3
      priority: 1
      role: judging
      api_key: "${NVIDIA_NIM_API_KEY}"
      base_url: "https://integrate.api.nvidia.com/v1"
    - provider: openai
      model: glm-4.7-flash
      priority: 2
      role: judging
      api_key: "${ZHIPU_API_KEY}"
      base_url: "https://open.bigmodel.cn/api/paas/v4"
  restoration:
    - provider: openai
      model: minimaxai/minimax-m3
      priority: 1
      role: restoration
      api_key: "${NVIDIA_NIM_API_KEY}"
      base_url: "https://integrate.api.nvidia.com/v1"
    - provider: openai
      model: glm-4.7-flash
      priority: 2
      role: restoration
      api_key: "${ZHIPU_API_KEY}"
      base_url: "https://open.bigmodel.cn/api/paas/v4"
"""


def _write_valid_config(tmp_path):
    """Generate a valid config via `ol init` (the real bootstrap path)."""
    cfg = tmp_path / "local.yaml"
    result = runner.invoke(
        app,
        ["init", "--non-interactive", "--force", "--config", str(cfg)],
        env=ENV,
    )
    assert result.exit_code == 0, (
        f"init failed: exit={result.exit_code}, out={result.output!r}"
    )
    return cfg


def test_doctor_pass_valid_config(tmp_path):
    """Scenario 4: valid config → exit 0, [PASS] on all 5 checks."""
    cfg = _write_valid_config(tmp_path)
    result = runner.invoke(app, ["doctor", "--config", str(cfg)], env=ENV)
    assert result.exit_code == 0, (
        f"exit={result.exit_code}, out={result.output!r}, exc={result.exception!r}"
    )
    assert "[PASS]" in result.output
    for name in CHECK_NAMES:
        assert name in result.output, f"check {name!r} missing from output"


def test_doctor_fail_one_model_role(tmp_path):
    """Scenario 5: 1-model translation role → exit 1, [FAIL] + 'run ol init' hint."""
    cfg = tmp_path / "local.yaml"
    cfg.write_text(ONE_MODEL_ROLE_YAML, encoding="utf-8")

    result = runner.invoke(app, ["doctor", "--config", str(cfg)], env=ENV)
    assert result.exit_code == ExitCode.PIPELINE_ERROR, (
        f"exit={result.exit_code}, out={result.output!r}"
    )
    assert "[FAIL]" in result.output
    assert "run 'ol init'" in result.output


def _unset_all_pool_env(monkeypatch, cfg):
    """Delete every pool var referenced by cfg, regardless of ambient state.

    Typer's CliRunner MERGES ``env=`` into ``os.environ`` rather than
    replacing it, so ambient provider keys (e.g. ``AMD_API_KEY`` from
    ``.env`` or the shell) survive into the command unless removed here.
    """
    refs = set(re.findall(r"\$\{([A-Z_][A-Z0-9_]*)\}", cfg.read_text(encoding="utf-8")))
    for var in refs:
        monkeypatch.delenv(var, raising=False)
    return refs


def test_doctor_fail_missing_env_var(tmp_path, monkeypatch):
    """Scenario 6: valid pool but every referenced ${VAR} unset → exit 1, env check FAIL."""
    cfg = _write_valid_config(tmp_path)

    # Neutralize loader._load_env_file: it loads Omni_Localizer/.env via a
    # FIXED path (loader.py:62-69) — NOT OL_DOTENV, NOT cwd — and would
    # re-introduce the provider key via os.environ.setdefault. Patch it out.
    import ol_config.loader as loader_mod

    monkeypatch.setattr(loader_mod, "_load_env_file", lambda: None)
    _unset_all_pool_env(monkeypatch, cfg)

    result = runner.invoke(app, ["doctor", "--config", str(cfg)], env=ENV)
    assert result.exit_code == ExitCode.PIPELINE_ERROR, (
        f"exit={result.exit_code}, out={result.output!r}"
    )
    assert "[FAIL]" in result.output
    assert "env vars resolve" in result.output


def test_doctor_pass_single_provider_key(tmp_path, monkeypatch):
    """BYOK: holding exactly one pool key → env check PASS, exit 0."""
    cfg = _write_valid_config(tmp_path)

    import ol_config.loader as loader_mod

    monkeypatch.setattr(loader_mod, "_load_env_file", lambda: None)
    refs = _unset_all_pool_env(monkeypatch, cfg)
    # Exactly one provider key — every other pool var stays unset.
    monkeypatch.setenv(sorted(refs)[0], "sk-dummy")

    result = runner.invoke(app, ["doctor", "--config", str(cfg)], env=ENV)
    assert result.exit_code == ExitCode.SUCCESS, (
        f"exit={result.exit_code}, out={result.output!r}"
    )
    assert "env vars resolve" in result.output
    assert "[FAIL]" not in result.output


def test_doctor_json_output(tmp_path):
    """Scenario 7: --json emits one parseable object with ok + 5 check keys."""
    cfg = _write_valid_config(tmp_path)
    result = runner.invoke(app, ["doctor", "--config", str(cfg), "--json"], env=ENV)
    assert result.exit_code == 0, (
        f"exit={result.exit_code}, out={result.output!r}, exc={result.exception!r}"
    )
    payload = json.loads(result.output)
    assert payload["ok"] is True
    assert set(payload["checks"].keys()) == set(JSON_KEYS)
    assert all(payload["checks"].values())


def test_doctor_in_help():
    """Scenario 8: `doctor` is registered and shows in `ol --help`."""
    result = runner.invoke(app, ["--help"], env=ENV)
    assert result.exit_code == 0
    assert "doctor" in result.output
